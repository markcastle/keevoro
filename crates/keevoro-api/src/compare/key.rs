//! Keevoro's key for Stratus's prices, which every request for them carries.
//!
//! The key is not a secret. Stratus asks programs to say who they are, and
//! the owner chose to ship it inside Keevoro, lightly hidden. It is kept
//! here as two lists of bytes that mean nothing alone, and put back
//! together only by [`stratus_key`], at the moment a request is made. That
//! keeps it from a casual look through the source or the program, and no
//! more. It is never logged, shown or sent anywhere but Stratus.

/// The key, mixed with [`MASK`] byte by byte.
const MIXED: [u8; 48] = [
    0x50, 0x87, 0x1e, 0x7f, 0xfa, 0xe9, 0xa3, 0xd0, 0xeb, 0xa5, 0x42, 0x9a, 0x62, 0xb1, 0x78, 0x97, 0xce, 0x4e, 0xbd,
    0x14, 0x5b, 0x28, 0xba, 0xc8, 0x5f, 0xbb, 0x6b, 0xd7, 0x63, 0xb5, 0x7a, 0x1f, 0xc6, 0x09, 0x66, 0x3b, 0x23, 0x43,
    0x14, 0xa7, 0x9c, 0x36, 0x61, 0x09, 0x59, 0x35, 0x49, 0xf8,
];

/// A fixed mask, of no meaning of its own.
const MASK: [u8; 48] = [
    0x23, 0xf3, 0x6c, 0x14, 0xa5, 0xde, 0x96, 0x84, 0xbc, 0xc3, 0x77, 0xa8, 0x16, 0x87, 0x10, 0xd2, 0xa9, 0x05, 0x85,
    0x55, 0x38, 0x4d, 0xd0, 0xa2, 0x3a, 0xc9, 0x19, 0xbf, 0x0f, 0xfa, 0x19, 0x2c, 0x88, 0x7a, 0x35, 0x0e, 0x74, 0x36,
    0x47, 0x93, 0xab, 0x65, 0x52, 0x68, 0x09, 0x45, 0x38, 0xb9,
];

/// Stratus's key for Keevoro, put back together from [`MIXED`] and
/// [`MASK`]. This only keeps it from a casual look: it is not a secret.
/// Call it only to fill in the header of a request to Stratus itself.
pub(super) fn stratus_key() -> String {
    MIXED
        .iter()
        .zip(MASK.iter())
        .map(|(mixed, mask)| char::from(mixed ^ mask))
        .collect()
}
